test('continuación no colisiona con códigos existentes y conserva una sola identidad',async({page})=>{
  await page.goto('/#/jornada');
  await page.getByLabel('Fecha de jornada').fill('2026-10-16');
  await page.getByRole('button',{name:'+ Tarea',exact:true}).click();
  await field(page,'Descripción').fill('Ya existente');
  await field(page,'Hora inicio').fill('10');
  await field(page,'Hora fin').fill('11');
  await field(page,'Descripción').focus();
  await createOvernight(page);
  await expect(page.locator('tbody tr')).toHaveCount(2);
  const codes = await page.locator('[data-grid="tasks"][data-col="0"]').evaluateAll(inputs=>inputs.map(input=>input.value));
  expect(new Set(codes).size).toBe(2);
  await expect(page.locator('tr.invalid')).toHaveCount(0);
  await field(page,'Descripción').fill('Noche editada');
  await page.getByRole('button',{name:'Día anterior',exact:true}).click();
  await expect(field(page,'Identificador')).toHaveValue('t1');
  await expect(field(page,'Descripción')).toHaveValue('Noche editada');
  await expect(page.locator('#saved')).toHaveText('Guardado');
  await page.reload();
  await page.getByLabel('Fecha de jornada').fill('2026-10-16');
  await expect(page.locator('tbody tr')).toHaveCount(2);
  const restored=await page.locator('[data-grid="tasks"][data-col="0"]').evaluateAll(inputs=>inputs.map(input=>input.value));
  expect(restored).toEqual(codes);
  const stored=await page.evaluate(()=>JSON.parse(localStorage.getItem('jornada.v1')));
  expect(stored.days['2026-10-16'].plan.tasks).toHaveLength(1);
});
for (const portion of ['primera','segunda']) {
  test(`eliminar ${portion} porción recorta el intervalo y Ctrl+Z restaura ambas`,async({page})=>{
    await createOvernight(page);
    if (portion === 'primera') await page.getByRole('button',{name:'Día anterior',exact:true}).click();
    const removedDay = portion === 'primera' ? '2026-10-15' : '2026-10-16';
    const keptDay = portion === 'primera' ? '2026-10-16' : '2026-10-15';
    await page.getByRole('button',{name:'Eliminar t1',exact:true}).click();
    await page.locator('dialog[open]').getByRole('button',{name:'Eliminar',exact:true}).click();
    await expect(page.locator('tbody tr')).toHaveCount(0);
    await expect(page.locator('#saved')).toHaveText('Guardado');
    await page.getByLabel('Fecha de jornada').fill(keptDay);
    await expect(page.locator('tbody tr')).toHaveCount(1);
    await expect(field(page,'Hora inicio')).toHaveValue(portion === 'primera' ? '00:00' : '21:00');
    await expect(field(page,'Hora fin')).toHaveValue(portion === 'primera' ? '02:00' : '24:00');
    await expect(field(page,'Duración')).toHaveValue(portion === 'primera' ? '02:00' : '03:00');
    await page.getByRole('button',{name:'Jornada',exact:true}).focus();
    await page.keyboard.press('Control+z');
    await page.getByLabel('Fecha de jornada').fill(removedDay);
    await expect(page.locator('tbody tr')).toHaveCount(1);
    await page.getByRole('button',{name:'Eliminar t1',exact:true}).click();
    await page.locator('dialog[open]').getByRole('button',{name:'Eliminar',exact:true}).click();
    await expect(page.locator('#saved')).toHaveText('Guardado');
    await page.reload();
    await page.getByLabel('Fecha de jornada').fill(removedDay);
    await expect(page.locator('tbody tr')).toHaveCount(0);
    await page.getByLabel('Fecha de jornada').fill(keptDay);
    await expect(page.locator('tbody tr')).toHaveCount(1);
    await expect(field(page,'Duración')).toHaveValue(portion === 'primera' ? '02:00' : '03:00');
  });
}
