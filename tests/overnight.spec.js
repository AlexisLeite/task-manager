import {test,expect} from '@playwright/test';
const field=(page,name)=>page.getByLabel(`Tarea 1: ${name}`,{exact:true});
async function createOvernight(page) {
  await page.goto('/#/jornada');
  await page.getByLabel('Fecha de jornada').fill('2026-10-15');
  await page.getByRole('button',{name:'+ Tarea',exact:true}).click();
  await field(page,'Descripción').fill('Trabajo nocturno');
  await field(page,'Hora inicio').fill('21');
  await field(page,'Hora fin').fill('02:00');
  await field(page,'Hora fin').press('Tab');
  await expect(page.getByLabel('Fecha de jornada')).toHaveValue('2026-10-16');
}
test('medianoche: una tarea, dos porciones, edición compartida y persistencia',async({page})=>{
  await createOvernight(page);
  await expect(field(page,'Hora inicio')).toHaveValue('00:00');
  await expect(field(page,'Hora fin')).toHaveValue('02:00');
  await expect(field(page,'Duración')).toHaveValue('02:00');
  await field(page,'Descripción').fill('Trabajo compartido');
  await field(page,'Hora fin').fill('03');
  await field(page,'Descripción').focus();
  await expect(field(page,'Duración')).toHaveValue('03:00');
  await expect(page.locator('#saved')).toHaveText('Guardado');
  const stored = await page.evaluate(()=>JSON.parse(localStorage.getItem('jornada.v1')));
  expect(stored.days['2026-10-15'].plan.tasks).toHaveLength(1);
  expect(stored.days['2026-10-15'].plan.tasks[0]).toMatchObject({estimate:'06:00',name:'Trabajo compartido'});
  expect(stored.days['2026-10-16'].plan.tasks).toHaveLength(0);
  await page.reload();
  await page.getByLabel('Fecha de jornada').fill('2026-10-16');
  await expect(field(page,'Hora fin')).toHaveValue('03:00');
  await page.getByRole('button',{name:'Día anterior',exact:true}).click();
  await expect(field(page,'Hora inicio')).toHaveValue('21:00');
  await expect(field(page,'Hora fin')).toHaveValue('24:00');
  await expect(field(page,'Duración')).toHaveValue('03:00');
  await expect(field(page,'Descripción')).toHaveValue('Trabajo compartido');
  await field(page,'Duración').focus();
  await field(page,'Descripción').focus();
  await page.getByRole('button',{name:'Día siguiente',exact:true}).click();
  await expect(field(page,'Hora fin')).toHaveValue('03:00');
});
test('completar desde la continuación reparte horas reales e Historia',async({page})=>{
  await createOvernight(page);
  await page.getByRole('button',{name:'Cambiar estado de t1',exact:true}).click();
  await page.getByRole('option',{name:'Completada',exact:true}).click();
  await expect(page.locator('#saved')).toHaveText('Guardado');
  const data=await page.evaluate(()=>JSON.parse(localStorage.getItem('jornada.v1')));
  expect(data.days['2026-10-15'].actual.blocks[0]).toMatchObject({start:'21:00',end:'24:00'});
  expect(data.days['2026-10-16'].actual.blocks[0]).toMatchObject({start:'00:00',end:'02:00'});
  await page.getByRole('button',{name:'Historia',exact:true}).click();
  await expect(page.locator('main')).toContainText('5:00');
});
test('Foco conserva la tarea al pasar medianoche y registra solo lo transcurrido',async({page})=>{
  await page.clock.setFixedTime(new Date('2026-10-16T01:00:00'));
  await createOvernight(page);
  await page.getByRole('button',{name:'Foco',exact:true}).click();
  await expect(page.locator('#focus-content')).toContainText('Trabajo nocturno');
  await page.getByLabel('Opciones de Trabajo nocturno').click();
  await page.getByRole('button',{name:'Terminar tarea',exact:true}).click();
  await expect(page.locator('#saved')).toHaveText('Guardado');
  const data=await page.evaluate(()=>JSON.parse(localStorage.getItem('jornada.v1')));
  expect(data.days['2026-10-15'].actual.blocks[0]).toMatchObject({start:'21:00',end:'24:00'});
  expect(data.days['2026-10-16'].actual.blocks[0]).toMatchObject({start:'00:00',end:'01:00'});
});

test('Enter confirma sin crear una segunda tarea, Foco antes de medianoche',async({page})=>{
  await page.clock.setFixedTime(new Date('2026-10-15T22:00:00'));
  await page.goto('/#/jornada');
  await page.getByLabel('Fecha de jornada').fill('2026-10-15');
  await page.getByRole('button',{name:'+ Tarea',exact:true}).click();
  await field(page,'Descripción').fill('Noche');
  await field(page,'Hora inicio').fill('21');
  await field(page,'Hora fin').fill('2');
  await field(page,'Hora fin').press('Enter');
  await expect(page.getByLabel('Fecha de jornada')).toHaveValue('2026-10-16');
  await expect(page.locator('tbody tr')).toHaveCount(1);
  await expect(page.locator('#saved')).toHaveText('Guardado');
  const data=await page.evaluate(()=>JSON.parse(localStorage.getItem('jornada.v1')));
  expect(data.days['2026-10-15'].plan.tasks).toHaveLength(1);
  expect(data.days['2026-10-15'].plan.tasks[0].estimate).toBe('05:00');
  await page.getByRole('button',{name:'Foco',exact:true}).click();
  await page.getByLabel('Opciones de Noche').click();
  await page.getByRole('button',{name:'Terminar tarea',exact:true}).click();
  await expect(page.locator('#saved')).toHaveText('Guardado');
  const done=await page.evaluate(()=>JSON.parse(localStorage.getItem('jornada.v1')));
  expect(done.days['2026-10-15'].actual.blocks[0]).toMatchObject({start:'21:00',end:'22:00'});
  expect(done.days['2026-10-16'].actual).toBeNull();
});

