import {test,expect} from '@playwright/test';

test('Jornada unificada edita horarios y navega con Ctrl+Shift sin depender del cursor',async({page},testInfo)=>{
  await page.goto('/#/jornada');
  await page.getByLabel('Fecha de jornada').fill('2026-10-15');
  await page.getByRole('button',{name:'Cargar ejemplo',exact:true}).click();
  await expect(page.locator('main table')).toHaveCount(1);
  await expect(page.locator('thead th')).toHaveText(['','Estado','Tarea','Descripción','Duración','Hora inicio','Hora fin','Proyecto','']);
  await page.locator('tbody tr').first().hover();
  await expect(page.locator('.linked-task-hover')).toHaveCount(0);
  expect(await page.locator('col.project-col').evaluate(el=>el.getBoundingClientRect().width)).toBeGreaterThanOrEqual(220);
  const field=(row,name)=>page.getByLabel(`Tarea ${row}: ${name}`,{exact:true});
  await field(1,'Descripción').focus();
  await field(1,'Descripción').evaluate(input=>input.setSelectionRange(8,8));
  await page.keyboard.press('Control+ArrowRight');
  await expect(field(1,'Descripción')).toBeFocused();
  await field(1,'Descripción').evaluate(input=>input.setSelectionRange(input.value.length,input.value.length));
  await page.keyboard.press('Control+ArrowRight');
  await expect(field(1,'Duración')).toBeFocused();
  await field(1,'Duración').fill('3');
  await page.keyboard.press('Control+Shift+ArrowRight');
  await expect(field(1,'Hora inicio')).toBeFocused();
  await field(1,'Hora inicio').fill('15');
  await page.keyboard.press('Control+Shift+ArrowRight');
  await expect(field(1,'Hora fin')).toBeFocused();
  await expect(field(1,'Hora inicio')).toHaveValue('15:00');
  await expect(field(1,'Duración')).toHaveValue('03:00');
  await expect(field(1,'Hora fin')).toHaveValue('18:00');
  await field(1,'Hora fin').fill('18:00');
  await page.keyboard.press('Control+Shift+ArrowLeft');
  await expect(field(1,'Hora inicio')).toBeFocused();
  await page.keyboard.press('Control+Shift+ArrowDown');
  await expect(field(2,'Hora inicio')).toBeFocused();
  await field(2,'Hora inicio').fill('17:00');
  await field(2,'Hora fin').focus();
  await expect(field(2,'Hora fin')).toHaveValue('19:30');
  await expect(field(3,'Hora inicio')).toHaveValue('16:30');
  await page.getByRole('button',{name:'Jornada',exact:true}).focus();
  await expect(field(2,'Identificador')).toHaveValue('t3');
  await expect(page.locator('#saved')).toHaveText('Guardado');
  await page.reload();
  await expect(field(1,'Hora fin')).toHaveValue('18:00');
  await expect(field(2,'Identificador')).toHaveValue('t3');
  await page.getByRole('button',{name:'Activar tema oscuro'}).click();
  await expect(page.locator('html')).toHaveCSS('background-color','rgb(25, 27, 30)');
  await page.screenshot({path:testInfo.outputPath('jornada-unificada.png'),fullPage:true});
});

test('alta, selección y cortar/pegar conservan tarea y horario',async({page})=>{
  await page.goto('/#/jornada');
  await page.getByRole('button',{name:'+ Tarea',exact:true}).click();
  await page.getByLabel('Tarea 1: Descripción',{exact:true}).fill('Nueva tarea');
  await page.getByLabel('Tarea 1: Hora inicio',{exact:true}).fill('9');
  await page.getByLabel('Tarea 1: Hora fin',{exact:true}).fill('10');
  await page.getByLabel('Tarea 1: Descripción',{exact:true}).focus();
  await expect(page.getByLabel('Tarea 1: Hora fin',{exact:true})).toHaveValue('10:00');
  await page.keyboard.press('Shift+Space');
  await page.keyboard.press('Control+x');
  await expect(page.locator('tbody tr')).toHaveCount(0);
  await page.keyboard.press('Control+v');
  await expect(page.locator('tbody tr')).toHaveCount(1);
  await expect(page.getByLabel('Tarea 1: Hora inicio',{exact:true})).toHaveValue('09:00');
  await expect(page.getByLabel('Tarea 1: Hora fin',{exact:true})).toHaveValue('10:00');
});

test('drag conserva el orden manual mientras se organiza y el proyecto se elige con teclado',async({page})=>{
  await page.addInitScript(()=>localStorage.setItem('jornada.v1',JSON.stringify({version:2,projects:[{id:'p',name:'Apia'}],tasks:[],days:{}})));
  await page.goto('/#/jornada');
  await page.getByRole('button',{name:'Cargar ejemplo',exact:true}).click();
  const name = row=>page.getByLabel(`Tarea ${row}: Descripción`,{exact:true});
  const original = await name(1).inputValue();
  await page.getByLabel('Seleccionar tarea 1',{exact:true}).dragTo(page.getByLabel('Seleccionar tarea 2',{exact:true}));
  await expect(name(2)).toHaveValue(original);
  const project=page.getByLabel('Tarea 2: Proyecto',{exact:true});
  await project.focus();
  await project.press('a');
  await page.getByLabel('Filtrar opciones',{exact:true}).press('Enter');
  await expect(project).toHaveValue('p');
  await name(2).focus();
  await name(2).evaluate(input=>input.setSelectionRange(5,5));
  await page.keyboard.press('Control+Shift+ArrowUp');
  await expect(name(1)).toBeFocused();
});

test('estado permite completar una cancelada del pasado y borrar sin perder horas registradas',async({page})=>{
  await page.goto('/#/jornada');
  await page.getByLabel('Fecha de jornada').fill('2026-10-10');
  await page.getByRole('button',{name:'Cargar ejemplo',exact:true}).click();
  const status=()=>page.getByRole('button',{name:'Cambiar estado de t1',exact:true});
  await status().click();
  await page.getByRole('option',{name:'Cancelada',exact:true}).click();
  await expect(page.getByRole('img',{name:'t1: Cancelada',exact:true})).toBeVisible();
  await status().click();
  await page.keyboard.press('Escape');
  await expect(page.getByLabel('Filtrar opciones')).toHaveCount(0);
  await status().click();
  await page.getByRole('option',{name:'Completada',exact:true}).click();
  await expect(page.getByRole('img',{name:'t1: Terminada',exact:true})).toBeVisible();
  await expect(page.locator('#saved')).toHaveText('Guardado');
  const actual=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('jornada.v1')).days['2026-10-10'].actual);
  const recorded=await actual();
  expect(recorded.blocks).toHaveLength(1);
  expect(recorded.blocks[0]).toMatchObject({start:'14:30',end:'16:30'});
  await page.getByRole('button',{name:'Eliminar t1',exact:true}).click();
  await expect(page.getByRole('dialog',{name:'Eliminar tarea'})).toBeVisible();
  await page.getByRole('button',{name:'Cancelar',exact:true}).click();
  await expect(page.locator('tbody tr')).toHaveCount(5);
  await page.getByRole('button',{name:'Eliminar t1',exact:true}).click();
  await page.locator('dialog[open]').getByRole('button',{name:'Eliminar',exact:true}).click();
  await expect(page.locator('tbody tr')).toHaveCount(4);
  await expect(page.locator('#saved')).toHaveText('Guardado');
  expect(await actual()).toEqual(recorded);
  await page.keyboard.press('Control+z');
  await expect(page.locator('tbody tr')).toHaveCount(5);
  await expect(page.getByRole('img',{name:'t1: Terminada',exact:true})).toBeVisible();
  await expect(page.locator('#saved')).toHaveText('Guardado');
  await page.reload();
  await page.getByLabel('Fecha de jornada').fill('2026-10-10');
  await expect(page.locator('tbody tr')).toHaveCount(5);
  expect(await actual()).toEqual(recorded);
  await page.getByRole('button',{name:'Historia',exact:true}).click();
  await expect(page.locator('main')).toContainText('2:00');
});


test('editar duración de una completada corrige realizado y estadísticas sin duplicar',async({page})=>{
  await page.goto('/#/jornada');
  await page.getByLabel('Fecha de jornada').fill('2026-10-15');
  await page.getByRole('button',{name:'+ Tarea',exact:true}).click();
  const field=name=>page.getByLabel(`Tarea 1: ${name}`,{exact:true});
  await field('Descripción').fill('Matriz');
  await field('Hora inicio').fill('18');
  await field('Hora fin').fill('20');
  await field('Descripción').focus();
  await page.getByRole('button',{name:'Cambiar estado de t1',exact:true}).click();
  await page.getByRole('option',{name:'Completada',exact:true}).click();
  await field('Duración').fill('6');
  await field('Descripción').focus();
  await expect(field('Hora fin')).toHaveValue('24:00');
  await expect(page.locator('#saved')).toHaveText('Guardado');
  const actual=await page.evaluate(()=>JSON.parse(localStorage.getItem('jornada.v1')).days['2026-10-15'].actual);
  expect(actual.blocks).toHaveLength(1);
  expect(actual.blocks[0]).toMatchObject({start:'18:00',end:'24:00'});
  expect(actual.tasks[0].estimate).toBe('06:00');
  await page.getByRole('button',{name:'Historia',exact:true}).click();
  await expect(page.locator('main')).toContainText('6:00');
});
