import { test, expect } from '@playwright/test';
import { example } from '../src/model.js';

test('opciones de grilla filtran al escribir, confirman con Enter y navegan celdas cerradas', async ({ page }) => {
  await page.addInitScript(plan => !localStorage.getItem('jornada.v1') && localStorage.setItem('jornada.v1', JSON.stringify({ version:2, projects:[{id:'a',name:'Apia'},{id:'b',name:'Backend'}], tasks:[], days:{'2026-10-15':{plan,actual:null}} })), example());
  await page.goto('/#/jornada');
  await page.getByLabel('Fecha de jornada').fill('2026-10-15');
  const project = page.getByLabel('Tarea 1: Proyecto', {exact:true});
  await project.focus();
  await page.keyboard.press('ArrowDown');
  await expect(page.getByLabel('Tarea 2: Proyecto', {exact:true})).toBeFocused();
  await page.keyboard.press('ArrowUp');
  await page.keyboard.press('b');
  const filter = page.getByLabel('Filtrar opciones', {exact:true});
  await expect(filter).toHaveValue('b');
  await expect(page.getByRole('option', {name:'Backend',exact:true}).filter({visible:true})).toHaveCount(1);
  await filter.press('Enter');
  await expect(project).toHaveValue('b');
  await expect(page.locator('.grid-options')).toHaveCount(0);
  await project.press('Enter');
  await filter.press('ArrowDown');
  await filter.press('Enter');
  await expect(project).toHaveValue('a');
  const priority = page.getByLabel('Tarea 1: Prioridad',{exact:true});
  await priority.focus();
  await page.keyboard.press('a');
  await filter.fill('alta');
  await filter.press('Enter');
  await expect(page.getByLabel('Tarea 1: Prioridad',{exact:true})).toHaveAttribute('data-priority-value','Alta');
  await page.keyboard.press('ArrowRight');
  await expect(page.locator('[data-grid="tasks"][data-row="0"][data-col="0"]')).toBeFocused();
  await project.focus();
  await project.press('Enter');
  await filter.fill('sin resultados');
  await expect(page.locator('#grid-options-list')).toHaveText('Sin coincidencias');
  await filter.press('Escape');
  await expect(project).toBeFocused();
  await expect(project).toHaveValue('a');
  await expect(page.locator('#saved')).toHaveText('Guardado');
  await page.reload();
  await expect(project).toHaveValue('a');
});
