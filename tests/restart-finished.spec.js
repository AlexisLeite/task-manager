import { test, expect } from '@playwright/test';
import { document as empty, task, block, union, normalizeDocument } from '../src/model.js';

test('Play copia una terminada; cambiar el tiempo y completar conserva los tramos anteriores', async ({ page }) => {
  await page.clock.install({time:new Date('2026-10-20T15:00:00')});
  await page.clock.pauseAt(new Date('2026-10-20T15:00:00'));
  const plan=empty(), original={...task([]),name:'Reglas',projectId:'p',estimate:'02:00'};
  const row={...block(),taskIds:[original.id],start:'10:00',end:'12:00',endDay:0,description:'Reglas',descriptionSource:'tasks',focusStates:{[original.id]:'finished'}};
  plan.tasks.push(original);plan.blocks.push(row);
  normalizeDocument(plan);
  const actual=structuredClone(plan);
  actual.blocks[0].sourceFocus=`${row.id}/${original.id}`;
  await page.addInitScript(data=>{
    if(!localStorage.getItem('jornada.v1'))localStorage.setItem('jornada.v1',JSON.stringify(data));
  },{version:2,tasks:[],projects:[{id:'p',name:'POC'}],days:{'2026-10-20':{plan,actual}}});
  await page.goto('/#/jornada');
  await page.getByRole('button',{name:`Iniciar ${original.code}`,exact:true}).click();
  await expect(page.locator('#saved')).toHaveText('Guardado');
  const read=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('jornada.v1')));
  let data=await read();
  expect(data.days['2026-10-20'].actual).toEqual(actual);
  expect(data.days['2026-10-20'].plan.blocks.find(b=>b.id===row.id)).toEqual(row);
  const copy=data.days['2026-10-20'].plan.tasks.find(t=>t.id!==original.id);
  expect(copy).toMatchObject({name:original.name,projectId:'p',taskId:original.taskId,estimate:''});
  expect(copy.code).not.toBe(original.code);
  await page.getByRole('button',{name:'Control del tiempo',exact:true}).click();
  await page.clock.runFor(500);
  const dialog=page.getByRole('dialog',{name:'Control del tiempo'});
  await dialog.getByLabel('Hora',{exact:true}).fill('14:00');
  await dialog.getByRole('button',{name:'Aplicar',exact:true}).click();
  await expect(page.locator('#saved')).toHaveText('Guardado');
  data=await read();
  expect(data.days['2026-10-20'].actual).toEqual(actual);
  expect(data.days['2026-10-20'].plan.blocks.find(b=>b.id===row.id)).toEqual(row);
  expect(data.days['2026-10-20'].plan.blocks.find(b=>b.taskIds.includes(copy.id)).start).toBe('16:00');
  await page.clock.fastForward(2*3600000);
  await page.getByRole('listitem').getByLabel('Opciones de Reglas',{exact:true}).click();
  await page.getByRole('button',{name:'Terminar tarea',exact:true}).click();
  await expect(page.locator('#saved')).toHaveText('Guardado');
  data=await read();
  expect(data.days['2026-10-20'].actual.blocks).toHaveLength(2);
  expect(data.days['2026-10-20'].actual.blocks.find(b=>b.sourceFocus===`${row.id}/${original.id}`)).toEqual(actual.blocks[0]);
  expect(union(data.days['2026-10-20'].actual.blocks)).toBe(180);
  await page.clock.fastForward(6.5*3600000);
  await page.getByRole('button',{name:'Jornada',exact:true}).click();
  await page.getByRole('button',{name:`Iniciar ${original.code}`,exact:true}).click();
  await page.clock.fastForward(3600000);
  await page.getByRole('button',{name:'Foco',exact:true}).click();
  await page.getByRole('listitem').getByLabel('Opciones de Reglas',{exact:true}).click();
  await page.getByRole('button',{name:'Terminar tarea',exact:true}).click();
  await expect(page.locator('#saved')).toHaveText('Guardado');
  data=await read();
  expect(union(data.days['2026-10-20'].actual.blocks)).toBe(210);
  expect(union(data.days['2026-10-21'].actual.blocks)).toBe(30);
  expect(data.days['2026-10-20'].actual.blocks.at(-1)).toMatchObject({start:'23:30',end:'24:00'});
  expect(data.days['2026-10-21'].actual.blocks[0]).toMatchObject({start:'00:00',end:'00:30'});
});
